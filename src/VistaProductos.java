    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {
            int codigo = Integer.parseInt(txtCodigo.getText().trim());
            Producto buscado = null;
            for (Producto p : MenuGeneral.listaProductos) {
                if (p.getCodigo() == codigo) {
                    buscado = p;
                    break;
                }
            }
            if (buscado != null) {
                txtDescripcion.setText(buscado.getDescripcion());
                txtPrecio.setText(String.valueOf(buscado.getPrecio()));
                txtStock.setText(String.valueOf(buscado.getStock()));
                cmbRubro.setSelectedItem(buscado.getRubro());

                txtCodigo.setEnabled(false);
                btnGuardar.setEnabled(false);
                btnActualizar.setEnabled(true);
                btnEliminar.setEnabled(true);
            } else {
                JOptionPane.showMessageDialog(this, "Producto no encontrado.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un código válido.");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            int codigo = Integer.parseInt(txtCodigo.getText().trim());
            String desc = txtDescripcion.getText().trim();
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            int stock = Integer.parseInt(txtStock.getText().trim());
            String rubro = cmbRubro.getSelectedItem().toString();

            if (desc.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Complete la descripción.");
                return;
            }

            Producto nuevo = new Producto(codigo, desc, precio, stock, rubro);
            if (!MenuGeneral.listaProductos.add(nuevo)) {
                JOptionPane.showMessageDialog(this, "Ya existe un producto con ese código.");
                return;
            }

            cargarTabla(cmbFiltrarRubro.getSelectedItem().toString());
            limpiarCampos();
            btnGuardar.setEnabled(false);
            JOptionPane.showMessageDialog(this, "Producto guardado con éxito.");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Verifique que los datos numéricos sean correctos.");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try {
            int codigo = Integer.parseInt(txtCodigo.getText().trim());
            Producto aEliminar = null;
            for (Producto p : MenuGeneral.listaProductos) {
                if (p.getCodigo() == codigo) {
                    aEliminar = p;
                    break;
                }
            }
            if (aEliminar != null) {
                MenuGeneral.listaProductos.remove(aEliminar);
                cargarTabla(cmbFiltrarRubro.getSelectedItem().toString());
                limpiarCampos();
                btnGuardar.setEnabled(false);
                btnActualizar.setEnabled(false);
                btnEliminar.setEnabled(false);
                JOptionPane.showMessageDialog(this, "Producto eliminado.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Seleccione un producto válido.");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

