    private void tblProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductosMouseClicked
        int fila = tblProductos.getSelectedRow();
        if (fila != -1) {
            txtCodigo.setText(tblProductos.getValueAt(fila, 0).toString());
            txtDescripcion.setText(tblProductos.getValueAt(fila, 1).toString());
            txtPrecio.setText(tblProductos.getValueAt(fila, 2).toString());
            cmbRubro.setSelectedItem(tblProductos.getValueAt(fila, 3).toString());
            txtStock.setText(tblProductos.getValueAt(fila, 4).toString());

            txtCodigo.setEnabled(false); // No editamos la clave primaria
            btnGuardar.setEnabled(false);
            btnActualizar.setEnabled(true);
            btnEliminar.setEnabled(true);
            }
    }//GEN-LAST:event_tblProductosMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
       try {
            int codigo = Integer.parseInt(txtCodigo.getText().trim());
            String desc = txtDescripcion.getText().trim();
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            int stock = Integer.parseInt(txtStock.getText().trim());
            String rubro = cmbRubro.getSelectedItem().toString();

            for (Producto p : MenuGeneral.listaProductos) {
                if (p.getCodigo() == codigo) {
                    p.setDescripcion(desc);
                    p.setPrecio(precio);
                    p.setStock(stock);
                    p.setRubro(rubro);
                    break;
                }
            }

            cargarTabla(cmbFiltrarRubro.getSelectedItem().toString());
            limpiarCampos();
            btnGuardar.setEnabled(false);
            btnActualizar.setEnabled(false);
            btnEliminar.setEnabled(false);
            JOptionPane.showMessageDialog(this, "Producto actualizado.");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Verifique los datos numéricos.");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed


