    private void comboBoxRubroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_comboBoxRubroActionPerformed
        int index = comboBoxRubro.getSelectedIndex();
        
        if(index > 0){
            modelo.setRowCount(0);
            for(Producto p: MenuGeneral.listaProductos){
                if(p.getRubro().equals(comboBoxRubro.getSelectedItem())){
                    modelo.addRow(new Object[]{
                        p.getCodigo(),
                        p.getDescripcion(),
                        p.getPrecio(),
                        p.getRubro(),
                        p.getStock()
                    });
                }
            }
        } else if (index == 0){
            cargarTabla();
        }
    }//GEN-LAST:event_comboBoxRubroActionPerformed


