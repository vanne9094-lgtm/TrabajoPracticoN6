    private void cargarCombo(){
        comboBoxRubro.removeAllItems();
        comboBoxRubro.addItem("Seleccione una categoria");
        comboBoxRubro.addItem("COMESTIBLE");
        comboBoxRubro.addItem("LIMPIEZA");
        comboBoxRubro.addItem("PERFUMERIA");
    }
    
    private void cargarCabecera(){
        modelo.addColumn("Código");
        modelo.addColumn("Descripción");
        modelo.addColumn("Precio");
        modelo.addColumn("Rubro");
        modelo.addColumn("Stock");
        
        tableConsultaPorRubro.setModel(modelo);
    }
    
    private void cargarTabla(){
        modelo.setRowCount(0);
        
        for(Producto p: MenuGeneral.listaProductos){
            modelo.addRow(new Object[]{
                p.getCodigo(),
                p.getDescripcion(),
                p.getPrecio(),
                p.getRubro(),
                p.getStock()
            });
        }
    }
